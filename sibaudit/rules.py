def render_json_catalog(rules: Sequence[Rule] | None = None) -> str:
    """Machine-readable catalog used by docs/catalog-v0.2.json."""
    from . import __version__

    selected = tuple(rules) if rules is not None else RULES
    payload = {
        "version": __version__,
        "rules": [
            {
                "code": rule.code,
                "severity": rule.severity,
                "title": rule.title,
                "rationale": rule.rationale,
                "flagged": rule.flagged,
                "fixed": rule.fixed,
            }
            for rule in selected
        ],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def _indent(text: str) -> str:
    return "\n".join(f"    {line}" if line else "" for line in text.rstrip().splitlines())


